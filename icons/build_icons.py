#!/usr/bin/env python3
"""Install the "Eink" icon theme and the title-bar button icons for Qt's adwaita decoration.

Usage: build_icons.py [ICONS_DIR]   (default: ~/.local/share/icons)

Eink is a thin wrapper. With Cawnonical Mono-Glyph (Text-Fill) installed it inherits that black glyph set;
without it, it chains GNOME's HighContrast and Adwaita. Breeze fills names either lacks.
"""
import os
import sys
from pathlib import Path

BUTTONS = ("minimize", "maximize", "restore", "close")
# Outline drawn around each 24 px title-bar button, like GTK4's high-contrast window controls.
RING = '    <circle cx="8" cy="8" r="11.5" fill="none" stroke="#000000" stroke-width="1"/>\n'
MONO_GLYPH = "Cawnonical Mono-Glyph Icon Suite (Text-Fill)"
MONO_GLYPH_URL = "https://store.kde.org/p/2298642"

OWNER_MARK = "# Generated by eink-qt-theming (icons/build_icons.py)."
INDEX_THEME = OWNER_MARK + """
[Icon Theme]
Name=Eink
Comment={comment}
Inherits={inherits}
FollowsColorScheme=true
# KIconLoader rejects themes without a valid directory (and ignores Context=UI ones); actions stays empty.
Directories=actions,mimetypes
# decoration/ is deliberately undeclared: only Qt's adwaita title bar scans for it by file name.

[actions]
Context=Actions
Size=16
MinSize=8
MaxSize=512
Type=Scalable

[mimetypes]
Context=MimeTypes
Size=16
MinSize=8
MaxSize=512
Type=Scalable
"""


def data_dirs():
    home = Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local/share")
    system = os.environ.get("XDG_DATA_DIRS") or "/usr/local/share:/usr/share"
    return [home] + [Path(d) for d in system.split(":") if d]


def theme_dirs(name, icons):
    return [d / name for d in [icons] + [d / "icons" for d in data_dirs()] if (d / name / "index.theme").is_file()]


def icon_files(theme):
    # Glyph sizes sort last so they win over the large illustrations.
    return {p.stem: p for p in sorted(theme.rglob("*.svg"), key=lambda p: "/glyphs/" in str(p))}


def read_map(path):
    return dict(line.split(":", 1) for line in path.read_text().splitlines() if ":" in line) if path.is_file() else {}


def mime_aliases(mono, icons):
    """File types Mono-Glyph has no icon for would get Breeze's coloured one; point them at its generic glyph."""
    have = icon_files(mono)
    coloured = set()
    for name in ("breeze", "hicolor"):
        for theme in theme_dirs(name, icons):
            coloured |= icon_files(theme).keys()
    aliases = {}
    for d in data_dirs():
        mime = d / "mime"
        if not (mime / "types").is_file():
            continue
        custom, generic = read_map(mime / "icons"), read_map(mime / "generic-icons")
        for mimetype in (mime / "types").read_text().split():
            name = custom.get(mimetype, mimetype.replace("/", "-"))
            fallback = generic.get(mimetype, mimetype.split("/")[0] + "-x-generic")
            if name not in have and name in coloured and fallback in have:
                aliases.setdefault(name, have[fallback])
    return aliases


def adwaita_ui():
    # adwaita-icon-theme moved these from scalable/ui to symbolic/ui in version 43.
    for d in data_dirs():
        for sub in ("symbolic/ui", "scalable/ui"):
            if (d / "icons/Adwaita" / sub / "window-close-symbolic.svg").is_file():
                return d / "icons/Adwaita" / sub
    sys.exit("Adwaita's window-*-symbolic.svg icons not found; install adwaita-icon-theme.")


def owned(theme):
    if theme.is_symlink():
        return False
    if not theme.exists():
        return True
    index = theme / "index.theme"
    text = index.read_text(errors="replace") if index.is_file() else ""
    # The decoration comment marks themes written before OWNER_MARK existed.
    return OWNER_MARK in text or "decoration/ is deliberately undeclared" in text


def main():
    icons = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / ".local/share/icons"
    theme, kicon = icons / "Eink", icons / "KIconEngine"
    if not owned(theme):
        sys.exit(f"{theme} wasn't created by eink-qt-theming; move it away or pass another ICONS_DIR.")
    if kicon.is_symlink():
        sys.exit(f"{kicon} is a symlink; refusing to write through it.")
    ui = adwaita_ui()
    (theme / "actions").mkdir(parents=True, exist_ok=True)
    (theme / "mimetypes").mkdir(exist_ok=True)
    (theme / "decoration").mkdir(exist_ok=True)
    for old in (theme / "mimetypes").iterdir():
        if old.is_symlink():
            old.unlink()

    mono = next(iter(theme_dirs(MONO_GLYPH, icons)), None)
    if mono:
        aliases = mime_aliases(mono, icons)
        for name, target in aliases.items():
            link = theme / "mimetypes" / f"{name}.svg"
            os.symlink(os.path.relpath(target, link.parent) if target.is_relative_to(icons) else target, link)
        index = INDEX_THEME.format(comment=f"{MONO_GLYPH} for Qt and KDE apps", inherits=f"{mono.name},breeze,hicolor")
    else:
        index = INDEX_THEME.format(comment="GNOME HighContrast and Adwaita first; Breeze only fills names they lack",
                                   inherits="HighContrast,Adwaita,breeze,hicolor")
    (theme / "index.theme").write_text(index)

    # The decoration looks up the icon theme by name, then the fallback theme; KDE apps report
    # "KIconEngine" and "breeze" there, so without this directory they get Breeze's chevrons.
    kicon.mkdir(exist_ok=True)
    for name in BUTTONS:
        svg = (ui / f"window-{name}-symbolic.svg").read_text()
        target = theme / "decoration" / f"window-{name}-symbolic.svg"
        target.write_text(svg.replace("</svg>", RING + "</svg>"))
        link = kicon / target.name
        if link.exists() and not link.is_symlink():
            print(f"Left {link} alone: it is a file, not one of our links.")
            continue
        if link.is_symlink():
            link.unlink()
        os.symlink(Path("..") / "Eink" / "decoration" / target.name, link)

    if mono:
        print(f"Eink icon theme (based on {mono.name}, {len(aliases)} file-type aliases) "
              f"and title-bar icons installed in {icons}")
    else:
        print(f"Eink icon theme (HighContrast/Adwaita/Breeze) and title-bar icons installed in {icons}")
        print(f"For one consistent black icon set, extract {MONO_GLYPH} from {MONO_GLYPH_URL} into {icons} and rerun.")


if __name__ == "__main__":
    main()
